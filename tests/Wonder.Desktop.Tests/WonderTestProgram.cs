using Wonder.Workspace;

namespace Wonder.Desktop.Tests;

internal static class WonderTestProgram
{
    public static int Main(string[] args)
    {
        if (args.Length == 2 && args[0] == "--wonder-instance-probe")
            return RunInstanceProbe(args[1]);
        return AutoGenerated.XunitAutoGeneratedEntryPoint.Main(args);
    }

    private static int RunInstanceProbe(string dataDirectory)
    {
        try
        {
            if (!LauncherInstanceGuard.TryAcquire(dataDirectory, out var instance, out var owner))
            {
                Console.WriteLine($"BLOCKED:{owner?.ProcessId}");
                return 23;
            }
            using (instance)
            {
                var store = new WorkspaceStore(Path.Combine(dataDirectory, "workspace.json"));
                var document = store.Load();
                document.Root ??= new LayoutNode { Area = new Area { Title = "initial" } };
                Console.WriteLine("READY");
                string? command;
                while ((command = Console.ReadLine()) is not null)
                {
                    if (command == "close")
                    {
                        store.Save(document);
                        return 0;
                    }
                    if (command.StartsWith("edit:", StringComparison.Ordinal))
                    {
                        document.Areas.First().Title = command[5..];
                        store.Save(document);
                        Console.WriteLine("SAVED");
                    }
                }
                return 0;
            }
        }
        catch (Exception error) when (error is IOException or UnauthorizedAccessException or ArgumentException or InvalidDataException)
        {
            Console.WriteLine($"ERROR:{error.GetType().Name}");
            return 24;
        }
    }
}
